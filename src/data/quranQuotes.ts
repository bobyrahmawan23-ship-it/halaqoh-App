export function getDailyDynamicQuote(dateStr?: string): QuranQuote {
  // If dateStr is provided (YYYY-MM-DD), use it to determine the deterministic index
  let dayOfYear = 0;
  if (dateStr) {
    const d = new Date(dateStr);
    const start = new Date(d.getFullYear(), 0, 0);
    const diff = d.getTime() - start.getTime();
    const oneDay = 1000 * 60 * 60 * 24;
    dayOfYear = Math.floor(diff / oneDay);
  } else {
    const now = new Date();
    const start = new Date(now.getFullYear(), 0, 0);
    const diff = now.getTime() - start.getTime();
    const oneDay = 1000 * 60 * 60 * 24;
    dayOfYear = Math.floor(diff / oneDay);
  }
  const index = Math.abs(dayOfYear) % QURAN_QUOTES.length;
  return QURAN_QUOTES[index];
}
